const SHARD_BBOX = OSM_SHARDS.map(function(s){
  let w = Infinity, so = Infinity, e = -Infinity, n = -Infinity;
  for(const r of s.rings){
    for(let i = 0; i < r.length; i += 2){
      if(r[i] < w) w = r[i];
      if(r[i] > e) e = r[i];
      if(r[i + 1] < so) so = r[i + 1];
      if(r[i + 1] > n) n = r[i + 1];
    }
  }
  return { w: w, s: so, e: e, n: n };
});

export function primaryOSMShard(){ return OSM_SHARDS[0]; }
export function osmShardById(id){
  for(const s of OSM_SHARDS){ if(s.id === id) return s; }
  return null;
}

function tileWestLon(x, z){ return x / Math.pow(2, z) * 360 - 180; }
function tileNorthLat(y, z){
  const n = Math.PI - 2 * Math.PI * y / Math.pow(2, z);
  return 180 / Math.PI * Math.atan(0.5 * (Math.exp(n) - Math.exp(-n)));
}

function pointInShard(si, lon, lat){
  const rings = OSM_SHARDS[si].rings;
  let inside = false;
  for(const r of rings){
    for(let i = 0, j = r.length - 2; i < r.length; j = i, i += 2){
      const xi = r[i], yi = r[i + 1], xj = r[j], yj = r[j + 1];
      if((yi > lat) !== (yj > lat) && lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}

function segCross(ax, ay, bx, by, cx, cy, dx, dy){
  const d1 = (bx - ax) * (cy - ay) - (by - ay) * (cx - ax);
  const d2 = (bx - ax) * (dy - ay) - (by - ay) * (dx - ax);
  const d3 = (dx - cx) * (ay - cy) - (dy - cy) * (ax - cx);
  const d4 = (dx - cx) * (by - cy) - (dy - cy) * (bx - cx);
  return ((d1 > 0) !== (d2 > 0)) && ((d3 > 0) !== (d4 > 0));
}

function shardEdgeCrossesRect(si, w, s, e, n){
  const rings = OSM_SHARDS[si].rings;
  for(const r of rings){
    for(let i = 0, j = r.length - 2; i < r.length; j = i, i += 2){
      const x1 = r[j], y1 = r[j + 1], x2 = r[i], y2 = r[i + 1];

      if((x1 < w && x2 < w) || (x1 > e && x2 > e) || (y1 < s && y2 < s) || (y1 > n && y2 > n)) continue;

      if((x1 >= w && x1 <= e && y1 >= s && y1 <= n) || (x2 >= w && x2 <= e && y2 >= s && y2 <= n)) return true;
      if(segCross(x1, y1, x2, y2, w, s, e, s)) return true;
      if(segCross(x1, y1, x2, y2, e, s, e, n)) return true;
      if(segCross(x1, y1, x2, y2, e, n, w, n)) return true;
      if(segCross(x1, y1, x2, y2, w, n, w, s)) return true;
    }
  }
  return false;
}

const SHARD_EDGE_BLEED_METERS = 5000;
const METERS_PER_DEG_LAT = 111320;

const shardRouteMemo = new Map();
const SHARD_ROUTE_MEMO_MAX = 8192;

export function osmShardsForTile(z, x, y){
  const key = z + '/' + x + '/' + y;
  const hit = shardRouteMemo.get(key);
  if(hit !== undefined) return hit;

  const rawN = tileNorthLat(y, z), rawS = tileNorthLat(y + 1, z);
  const epsLat = SHARD_EDGE_BLEED_METERS / METERS_PER_DEG_LAT;

  const cosLat = Math.max(0.05, Math.cos((rawN + rawS) * 0.5 * Math.PI / 180));
  const epsLon = epsLat / cosLat;
  const w = tileWestLon(x, z) - epsLon;
  const e = tileWestLon(x + 1, z) + epsLon;
  const n = rawN + epsLat;
  const s = rawS - epsLat;

  const out = [];
  for(let si = 0; si < OSM_SHARDS.length; si++){
    const bb = SHARD_BBOX[si];
    if(e < bb.w || w > bb.e || n < bb.s || s > bb.n) continue;

    const claims =
      pointInShard(si, (w + e) * 0.5, (s + n) * 0.5) ||
      pointInShard(si, w, s) || pointInShard(si, e, s) ||
      pointInShard(si, w, n) || pointInShard(si, e, n) ||
      shardEdgeCrossesRect(si, w, s, e, n);
    if(claims) out.push(OSM_SHARDS[si]);
  }

  if(shardRouteMemo.size >= SHARD_ROUTE_MEMO_MAX) shardRouteMemo.clear();
  shardRouteMemo.set(key, out);
  return out;
}

export function osmShardsForLatLon(lat, lon){
  const out = [];
  for(let si = 0; si < OSM_SHARDS.length; si++){
    const bb = SHARD_BBOX[si];
    if(lon < bb.w || lon > bb.e || lat < bb.s || lat > bb.n) continue;
    if(pointInShard(si, lon, lat)) out.push(OSM_SHARDS[si]);
  }
  return out;
}

export function osmCoverageSummary(){
  return OSM_SHARDS.map(function(s){ return s.label + ' ' + s.vintage; }).join(' + ');
}

export function describeOSMShardRoute(z, x, y){
  const shards = osmShardsForTile(z, x, y);
  return {
    tile: z + '/' + x + '/' + y,
    west: tileWestLon(x, z), east: tileWestLon(x + 1, z),
    north: tileNorthLat(y, z), south: tileNorthLat(y + 1, z),
    shardIds: shards.map(function(s){ return s.id; }),
    seam: shards.length > 1,
    covered: shards.length > 0,
  };
}

export function getOSMShardRouteStats(){
  return { memoSize: shardRouteMemo.size, memoMax: SHARD_ROUTE_MEMO_MAX, shardCount: OSM_SHARDS.length };
}
